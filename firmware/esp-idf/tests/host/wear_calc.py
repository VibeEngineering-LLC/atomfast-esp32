# Расчёт износа флеша (модель, не измерение). Формула в отчёте littlefs-report.md.
import sys
RAW_BPS, AGG_BPS = 20 / 2.0, 28 / 60.0          # Б/с: сырая запись 20 Б раз в 2 с, агрегат 28 Б раз в минуту
D = (RAW_BPS + AGG_BPS) * 86400                  # Б/сутки на флеш
C = 100000                                       # циклов стирания сектора (типовое по даташиту NOR, НЕ измерено)
COMMIT_ER = 1 / 32                               # коммит метаданных = prog 128 Б из блока 4096 Б => 1/32 стирания
ROTATE = 4.0                                     # создание/удаление сегментов (~30 файлов/сут * 4 коммита / 32), стираний/сут
def erases_day(n_min):
    f = 1440 / n_min                             # сбросов в сутки
    return f * (2 + 2 * COMMIT_ER) + D / 4096 + ROTATE   # 2 файла * копия хвостового блока + метаданные + заполнение блоков
print(f"D = {D:.0f} Б/сут; raw {RAW_BPS*86400:.0f}, agg {AGG_BPS*86400:.0f}")
for n_eff, name in ((3040, "A все 3040 блоков"), (1100, "B только кольцо 1100 бл."), (100, "C худший 100 бл.")):
    row = []
    for n in (1, 2, 5, 10, 15, 30):
        e = erases_day(n)
        row.append(f"N={n}: {e:.0f} ст/сут, {n_eff * C / e / 365:.0f} лет")
    print(name + " | " + " | ".join(row))
nmin = lambda n_eff, years: next(n / 10 for n in range(1, 3000) if n_eff * C / erases_day(n / 10) / 365 >= years)
print("N_min для >=10 лет (худший C):", nmin(100, 10), "мин")

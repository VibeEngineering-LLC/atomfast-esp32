#pragma once
/* e10: датчики воздуха по I2C. e15: СПИСОК датчиков (до 8, номера 1..8, модели bmp280/bme280/sht3x/aht2x), настройки в NVS, JSON для /api/sensors. */
#include <stddef.h>
#include <stdint.h>
#include "af_env.h"
#include "af_sns_reg.h"

/* Старт: прочитать реестр из NVS (при порче или отсутствии - миграция со старых ключей либо значения по умолчанию) и запустить задачу измерения. Безопасен при ошибках. */
void af_env_drv_start(void);
/* Копия реестра (список датчиков и agg_s). До старта драйвера - значения по умолчанию. */
void af_env_drv_get_reg(af_sns_reg_t *r);
/* Номер основного датчика для старого API без поля sensor: 1, если он есть, иначе первый по порядку; 0 - датчиков нет. */
uint8_t af_env_drv_primary(void);
/* Изменить один датчик (patch проверяется af_sns_reg_patch). 0 принято; -1 нет датчика; -2 неверные значения; -3 драйвер не запущен. *persisted: 1 записано в NVS, 0 действует до перезагрузки. */
int af_env_drv_patch(uint8_t sensor, const af_sns_patch_t *p, int *persisted);
/* Общий период усреднения живых данных, 1..60 с. 0 принято; -2 неверно; -3 драйвер не запущен. */
int af_env_drv_set_agg(int32_t agg_s, int *persisted);
/* Включить/выключить все датчики модели (model = af_sns_model_t). Возврат: число затронутых датчиков (может быть 0); -1 неверная модель; -2 неверное enabled; -3 драйвер не запущен. */
int af_env_drv_enable_model(uint8_t model, uint8_t enabled, int *persisted);
/* Добавить датчик вручную. Возврат: номер 1..8; -1 неверные модель/адрес; -2 адрес занят; -3 список полон; -4 драйвер не запущен. */
int af_env_drv_add(uint8_t model, uint8_t addr, uint8_t enabled, int *persisted);
/* Удалить датчик по номеру. 0 ок; -1 нет такого; -3 драйвер не запущен. */
int af_env_drv_remove(uint8_t sensor, int *persisted);
/* I2C-скан по кнопке: ищет известные адреса, добавляет найденные ВЫКЛЮЧЕННЫМИ, дублей не создаёт. Выполняется в задаче датчиков; ждёт до ~3 с. 0 готово (*found - найдено, *changed - добавлено/изменено); -1 занято или таймаут; -3 драйвер не запущен. */
int af_env_drv_scan(int *found, int *changed);
/* Тело ответа GET /api/sensors (JSON). Возврат длины или -1, если не поместилось в cap. */
int af_env_drv_json(char *buf, size_t cap);
/* e12: последние показанные (с поправкой) значения воздуха и маска возможностей (AF_CAP_*): температура и давление берутся с первых по порядку датчиков, у которых они есть. NaN - нет значения. 0 - ок, -1 - драйвер не запущен. */
int af_env_drv_get_air(float *t_c, float *p_mmhg, uint8_t *caps);
